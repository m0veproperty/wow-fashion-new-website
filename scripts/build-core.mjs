import {mkdir,writeFile,rm} from 'node:fs/promises';
import {buildCatalog} from './core-catalog.mjs';
import {renderDiscoveryPages} from './core-discovery.mjs';
import {renderContentPages} from './core-content.mjs';
import {renderCommercePages} from './core-commerce.mjs';
import {renderCorePage} from './core-shell.mjs';
import {corePages} from '../portal/public/core-pages.js';

const origin='https://wow-fashion-new-website.vercel.app';

export async function buildCorePages({departments,campaignHeroes}) {
  const catalog=buildCatalog({departments,campaignHeroes});
  const pages=[
    ...renderDiscoveryPages({catalog,corePages}),
    ...renderContentPages({catalog,corePages}),
    ...renderCommercePages({catalog,corePages})
  ];
  const pageIds=new Set(),paths=new Set(['/']);
  for(const page of pages) {
    if(pageIds.has(page.id))throw new Error('Duplicate core page ID: '+page.id);
    if(paths.has(page.path))throw new Error('Duplicate core page route: '+page.path);
    if(!/^\/[a-z0-9\/-]+\/$/.test(page.path)||page.path.includes('..'))throw new Error('Invalid core page route: '+page.path);
    pageIds.add(page.id);paths.add(page.path);
    const systemCode=page.id==='core-404'?404:page.id==='core-error'?503:null;
    // Vercel checks static files before rewrites. Keep the function documents
    // away from their public routes, including on a repeated local build.
    if(systemCode)await rm('dist'+page.path,{recursive:true,force:true});
    const folder=systemCode?'dist/_system/':'dist'+page.path;
    await mkdir(folder,{recursive:true});
    const html=renderCorePage(page);
    await writeFile(folder+(systemCode?systemCode+'.html':'index.html'),html);
    if(page.id==='core-404')await writeFile('dist/404.html',html);
  }
  const missing=corePages.filter(page=>page.id!=='core-home'&&!pageIds.has(page.id));
  if(missing.length)throw new Error('Missing core pages: '+missing.map(page=>page.id).join(', '));
  const home={id:'core-home',path:'/',status:'Built',dependencies:[]};
  const definitions=new Map([home,...pages].map(page=>[page.id,page]));
  const builds=Object.fromEntries(corePages.map(page=>{
    const built=definitions.get(page.id);
    return [page.id,{
      path:built.path,
      url:origin+built.path,
      status:built.status==='Built'?'Built preview':built.status,
      dependencies:built.dependencies||[],
      reviewedOn:'2026-11-08'
    }];
  }));
  const manifest={schemaVersion:1,site:origin,corePageCount:corePages.length,additionalPages:pages.filter(page=>!corePages.some(core=>core.id===page.id)).map(({id,path,title})=>({id,path,title})),catalogue:catalog.mapAudit,pages:builds};
  await mkdir('dist/data',{recursive:true});
  await writeFile('dist/data/shop-catalog.json',JSON.stringify(catalog));
  await writeFile('dist/data/core-page-builds.json',JSON.stringify(manifest,null,2)+'\n');
  await writeFile('portal/public/data/core-page-builds.js','// Generated by scripts/build-core.mjs. Public preview metadata; shared page plans are stored separately.\nexport const corePageBuilds = '+JSON.stringify(builds,null,2)+';\n');
  console.log(`Built all ${corePages.length} core page previews, ${manifest.additionalPages.length} additional articles and a ${catalog.products.length}-piece catalogue.`);
  return manifest;
}
